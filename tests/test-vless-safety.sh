#!/bin/sh

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
TMP=$(mktemp -d "${TMPDIR:-/tmp}/kvas-safety-test.XXXXXX")
trap 'rm -rf "$TMP"' EXIT HUP INT TERM

sh -n "$ROOT/opt/bin/libs/vpn"
sh -n "$ROOT/opt/bin/libs/vless"
sh -n "$ROOT/opt/etc/ndm/ndm"

grep -Fq 'state=$(get_value_interface_field "${inface_cli}" state)' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'link=$(get_value_interface_field "${inface_cli}" link)' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'connected=$(get_value_interface_field "${inface_cli}" connected)' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'update_iptables || exit 1' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'VLESS: вспомогательный /24 маршрут' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'VLESS_CONFIG_FILE=/opt/etc/xray/kvas.json' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'kvas-rules.lock' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'if is_vless_over_proxy_enabled ; then' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'ip4__mark__create_chain || return 1' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'Не удалось создать policy rule' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'return 1' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'XRAY_INIT=/opt/etc/init.d/S97xray' "$ROOT/opt/bin/libs/vless"
! grep -Fq "service_restart 'клиент VLESS' 'S24xray'" "$ROOT/opt/bin/libs/vpn"
grep -Fq 'RULE_PRIORITY=99' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'Не передёргивать Proxy21 через RCI' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'обязательная проверка Proxy21 или SOCKS5 не прошла' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'xray_runtime_ready' "$ROOT/opt/bin/libs/vless"
grep -Fq 'pidof xray' "$ROOT/opt/bin/libs/vless"
grep -Fq '127\\.0\\.0\\.1:${PROXY_VLESS_PORT}' "$ROOT/opt/bin/libs/vless"
grep -Fq 'S97xray завершился или не открыл SOCKS-порт 1097' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'повторный RCI-up VLESS запрещён' "$ROOT/opt/etc/ndm/iflayerchanged.d/100-kvas-vpn"
grep -Fq 'пересборка KVAS-правил для VLESS пропущена' "$ROOT/opt/etc/ndm/iflayerchanged.d/100-kvas-vpn"
grep -Fq 'пересборка KVAS-правил для VLESS пропущена' "$ROOT/opt/etc/ndm/iflayerchanged.d/kvas-ips-reset"
grep -Fq 'повторный link_reboot и пересборка KVAS-правил для VLESS запрещены' "$ROOT/opt/etc/ndm/ifstatechanged.d/100-kvas-vpn"
grep -Fq 'повторный link_reboot VLESS запрещён' "$ROOT/opt/etc/ndm/iflayerchanged.d/kvas-ips-reset"
grep -Fq 'RCI down/up Proxy21 запрещён' "$ROOT/opt/bin/main/check_vpn"
grep -Fq 'Переключение не прошло; конфигурация не подтверждена' "$ROOT/opt/bin/kvas"
grep -Fq 'prepare_vless_rollback' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'vless_fail_closed' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'ip rule del priority 99' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'default dev "${failed_ent}" table 1001' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'Автоматический откат не выполнялся' "$ROOT/opt/bin/libs/vpn"
grep -Fq -- '--connect-timeout 3 --max-time 8' "$ROOT/opt/bin/libs/vless"
grep -Fq -- '--socks5-hostname "${LOCALHOST_IP}:${PROXY_VLESS_PORT}"' "$ROOT/opt/bin/libs/vless"
grep -Fq 'прямой тест через' "$ROOT/opt/bin/libs/vless"
grep -Fq 'диагностический' "$ROOT/opt/bin/libs/vless"
grep -Fq -- 'return "${_status}"' "$ROOT/opt/bin/libs/vless"
grep -Fq -- '--connect-timeout 3 --max-time 15' "$ROOT/opt/bin/libs/vpn"
! grep -Fq 'service_action S97xray start' "$ROOT/opt/bin/kvas"
grep -Fq 'switch_vpn_on' "$ROOT/opt/apps/kvas/rescue/kvas-vless-rollback.sh"
sh -n "$ROOT/opt/apps/kvas/rescue/kvas-vless-rollback.sh"
test -x "$ROOT/opt/apps/kvas/rescue/kvas-vless-rollback.sh"
grep -Fq 'VLESS_CONFIG_FILE_BACKUP' "$ROOT/opt/bin/kvas"
grep -Fq 'failover daemon не запускается' "$ROOT/opt/bin/kvas"
grep -Fq 'KVAS_SET_SWITCH=yes' "$ROOT/opt/bin/kvas"
grep -Fq 'Повторный cmd_kvas_init здесь перезапускает Xray' "$ROOT/opt/bin/libs/vpn"
grep -Fq 'echo "[${_ts}] ${1}"' "$ROOT/opt/bin/libs/main"
grep -Fq 'ip4__wan_route_is_ready' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'Фактический WAN route недоступен' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'attempt=1' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'sleep 1' "$ROOT/opt/etc/ndm/ndm"
grep -Fq 'Нет mapping для' "$ROOT/opt/bin/kvas"
grep -Fq 'failover_mapping' "$ROOT/opt/bin/libs/failover"
grep -Fq 'Не вмешиваться в вручную выбранный OpenVPN' "$ROOT/opt/bin/libs/failover"

ipk=$("$ROOT/tools/build-ipk.sh" --compat-352 --output "$TMP")
"$ROOT/tools/verify-compat-ipk.sh" "$ipk"

printf '%s\n' 'OK: проверки безопасности VLESS и сборки IPK пройдены'
